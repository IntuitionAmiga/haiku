void
Crypt(const XtsVector& vector, bool encrypt)
{
	xts_haiku_context context;
	CPPUNIT_ASSERT(xts_haiku_init(&context, vector.key.data(),
		vector.key.size()) == 0);

	Block32 buffer = encrypt ? vector.plaintext : vector.ciphertext;
	const Block32& expected = encrypt ? vector.ciphertext : vector.plaintext;

	CPPUNIT_ASSERT(xts_haiku_crypt(&context, 0, vector.dataUnit.data(),
		buffer.data(), buffer.size(), encrypt) == 0);
	CPPUNIT_ASSERT(std::equal(buffer.begin(), buffer.end(), expected.begin()));

	xts_haiku_clear(&context);
}

void
Crypt(const XtsVector256& vector, bool encrypt)
{
	xts_haiku_context context;
	CPPUNIT_ASSERT(xts_haiku_init(&context, vector.key.data(),
		vector.key.size()) == 0);

	Block32 buffer = encrypt ? vector.plaintext : vector.ciphertext;
	const Block32& expected = encrypt ? vector.ciphertext : vector.plaintext;

	CPPUNIT_ASSERT(xts_haiku_crypt(&context, 0, vector.dataUnit.data(),
		buffer.data(), buffer.size(), encrypt) == 0);
	CPPUNIT_ASSERT(std::equal(buffer.begin(), buffer.end(), expected.begin()));

	xts_haiku_clear(&context);
}

