CppUnit::Test*
XtsKatTest::Suite()
{
	CppUnit::TestSuite* suite = new CppUnit::TestSuite("XtsKatTest");
	typedef CppUnit::TestCaller<XtsKatTest> TestCaller;

	suite->addTest(new TestCaller("IEEE1619 XTS-AES-128 encrypt",
		&XtsKatTest::TestIeee1619XtsAes128Encrypt));
	suite->addTest(new TestCaller("IEEE1619 XTS-AES-128 decrypt",
		&XtsKatTest::TestIeee1619XtsAes128Decrypt));
	suite->addTest(new TestCaller("NIST XTS-AES-256 encrypt",
		&XtsKatTest::TestNistXtsAes256Encrypt));
	suite->addTest(new TestCaller("NIST XTS-AES-256 decrypt",
		&XtsKatTest::TestNistXtsAes256Decrypt));
	suite->addTest(new TestCaller("invalid key length rejected",
		&XtsKatTest::TestRejectInvalidKeyLength));

	return suite;
}


void
XtsKatTest::TestIeee1619XtsAes128Encrypt()
{
	for (const XtsVector& vector : kXts128Vectors)
		Crypt(vector, true);
}


void
XtsKatTest::TestIeee1619XtsAes128Decrypt()
{
	for (const XtsVector& vector : kXts128Vectors)
		Crypt(vector, false);
}


void
XtsKatTest::TestNistXtsAes256Encrypt()
{
	Crypt(kXts256Vector, true);
}


void
XtsKatTest::TestNistXtsAes256Decrypt()
{
	Crypt(kXts256Vector, false);
}


void
XtsKatTest::TestRejectInvalidKeyLength()
{
	xts_haiku_context context;
	const std::array<uint8_t, 48> invalidKey = {};
	CPPUNIT_ASSERT(xts_haiku_init(&context, invalidKey.data(),
		invalidKey.size()) != 0);
}
